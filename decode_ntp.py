import binascii

hex_strings = [
"23020a0000000000000000007f0000016553f162000000006553f179000000006553f175000000006553f16300000000",
"23020a0000000000000000007f0000016553f174000000006553f166000000006553f17b000000006553f15300000000",
"23020a0000000000000000007f0000016553f130000000006553f15f000000006553f14d000000006553f17900000000",
"23020a0000000000000000007f0000016553f15f000000006553f150000000006553f134000000006553f17200000000",
"23020a0000000000000000007f0000016553f134000000006553f164000000006553f130000000006553f17800000000",
"23020a0000000000000000007f0000016553f15f000000006553f121000000006553f164000000006553f13300000000",
"23020a0000000000000000007f0000016553f134000000006553f15f000000006553f144000000006553f12100000000",
"23020a0000000000000000007f0000016553f164000000006553f16e000000006553f174000000006553f15f00000000",
"23020a0000000000000000007f0000016553f157000000006553f130000000006553f172000000006553f16b00000000",
"23020a0000000000000000007f0000016553f17d000000006553f100000000006553f100000000006553f10000000000"
]

out = ""
for hs in hex_strings:
    b = binascii.unhexlify(hs)
    # the format seems to be 6553f1XX where XX is the character, followed by 00000000
    for i in range(16, len(b), 8):
        char_hex = hs[i*2+6:i*2+8]
        if char_hex != '00':
            out += chr(int(char_hex, 16))

print(f"Decoded: {out}")
